    (r'પર્યાય\s+બદલાતી\s+રહે\s+છે\b', 'પર્યાય બદલાતો રહે છે'),
    (r'પર્યાય\s+વહેતી\s+રહે\s+છે\b', 'પર્યાય વહેતો રહે છે'),
    
    # Plural Verbs
    (r'પર્યાયો\s+બદલાઈ\b', 'પર્યાયો બદલાયા'),
    (r'પર્યાયો\s+નષ્ટ\s+થઈ\b', 'પર્યાયો નષ્ટ થયા'),
    (r'પર્યાયો\s+ઉત્પન્ન\s+થઈ\b', 'પર્યાયો ઉત્પન્ન થયા'),

    (r'પર્યાય\s+બદલાઈ\b', 'પર્યાય બદલાયો'),
    (r'પર્યાય\s+પલટાઈ\b', 'પર્યાય પલટાયો'),
    (r'પર્યાય\s+પ્રગટ\s+થઈ\b', 'પર્યાય પ્રગટ થયો'),
    (r'પર્યાય\s+પ્રગટ\s+થવાની\s+છે\b', 'પર્યાય પ્રગટ થવાનો છે'),
    (r'પર્યાય\s+પ્રગટી\b', 'પર્યાય પ્રગટ્યો'),

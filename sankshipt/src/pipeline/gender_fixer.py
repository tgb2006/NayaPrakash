    (r'ગુણની\s+પર્યાય\b', 'ગુણનો પર્યાય'),
    (r'સમયની\s+પર્યાય\b', 'સમયનો પર્યાય'),
    (r'અતીતની\s+પર્યાય\b', 'અતીતનો પર્યાય'),
